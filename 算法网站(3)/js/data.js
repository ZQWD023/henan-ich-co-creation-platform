// 提取地区中的地级市名（如 "郑州市登封市" → "郑州"，"郑州市·开封市" → "郑州"）
function cityOf(region) {
    return (region || '').split(/[·・]/)[0].split('市')[0];
}

// ============ 数据访问对象 ============
const ICH = {
    categories: ichCategories,
    projects: heritageProjects,
    inheritors: inheritors,
    works: coCreateWorks,
    events: events,
    news: news,
    achievements: ichAchievements,

    // 获取分类
    getCategory: function (id) {
        return this.categories.find(c => c.id === id) || null;
    },

    // 获取项目
    getProject: function (id) {
        return this.projects.find(p => p.id === id) || null;
    },

    // 获取分类下的项目
    getProjectsByCategory: function (categoryId) {
        return this.projects.filter(p => p.category === categoryId);
    },

    // 按保护级别筛选
    getProjectsByLevel: function (level) {
        if (!level || level === 'all') return this.projects;
        return this.projects.filter(p => p.level === level);
    },

    // 获取传承人
    getInheritor: function (id) {
        return this.inheritors.find(i => i.id === id) || null;
    },

    // 获取项目的传承人
    getInheritorsByProject: function (projectId) {
        return this.inheritors.filter(i => i.projectId === projectId);
    },

    // 搜索项目
    searchProjects: function (query) {
        const q = (query || '').toLowerCase().trim();
        if (!q) return this.projects;
        return this.projects.filter(p => {
            const cat = this.getCategory(p.category);
            const text = (p.name + p.brief + p.region + p.level + (cat ? cat.name : '') + p.tags.join('')).toLowerCase();
            return text.includes(q);
        });
    },

    // 精选项目（按热度）
    getFeaturedProjects: function (count) {
        return [...this.projects].sort((a, b) => (b.popularity || 0) - (a.popularity || 0)).slice(0, count || 6);
    },

    // 全部地区（地级市名）
    getAllRegions: function () {
        const regions = new Set();
        this.projects.forEach(p => regions.add(cityOf(p.region)));
        return Array.from(regions).sort((a, b) => a.localeCompare(b, 'zh-CN'));
    },

    // 项目总数与统计
    getStats: function () {
        const national = this.projects.filter(p => p.level === '国家级').length;
        const provincial = this.projects.filter(p => p.level === '省级').length;
        return {
            total: this.projects.length,
            national: national,
            provincial: provincial,
            inheritors: this.inheritors.length,
            works: this.works.length
        };
    }
};

